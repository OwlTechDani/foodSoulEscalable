const router = require('express').Router();
const { auth, admin } = require('../middleware/auth');
const run = require('../helpers/async');
const c = require('../controllers/admin');
router.get('/catalog', run(c.listCatalog));
router.use(auth, admin);
router.get('/users', run(c.listUsers));
router.put('/users/:id', run(c.updateUser));
router.post('/catalog', run(c.saveCatalog));
router.put('/catalog/:id', run(c.saveCatalog));
router.delete('/catalog/:id', run(c.deleteCatalog));
module.exports = router;
